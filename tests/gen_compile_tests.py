#!/usr/bin/env python3
"""
Generate one compile-test TU per named configuration.

One TU per configuration on purpose: when a static_assert fires, the compiler's
"in instantiation of" trail names that configuration, and one bad config cannot
hide the others behind a single translation unit.

Run via tests/CMakeLists.txt, which globs the .cpp files this writes.
"""
import argparse
import pathlib
import sys

PRESETS = ['P64X32_1_16', 'P64X64_1_32', 'P80X40_1_20', 'P96X48_1_24', 'P96X48_1_24_SR']


def preset(name, **kw):
    """Overlay fields on top of a named preset, in Hub75Config declaration order."""
    parts = [f'.{key} = {{{kw[key]}}}' for key in ('panel', 'screen', 'pins', 'color') if kw.get(key)]
    return (f'make_hub75_config(Hub75PanelProfile::{name}, Hub75Config{{'
            + ', '.join(parts) + '})')


# Axes worth covering that the presets themselves do not vary.
CASES = {
    # --- bit depth: BCM sequence and CCM_MAX_VAL both branch on this ---
    'bp8':              preset('P64X64_1_32', color='.bitplanes = 8'),
    'bp8_nobalanced':   preset('P64X64_1_32', color='.bitplanes = 8, .balanced_light_output = false'),
    'bp10_nobalanced':  preset('P64X64_1_32', color='.bitplanes = 10, .balanced_light_output = false'),
    'separate_cie':     preset('P64X64_1_32', color='.separate_cie_channels = true'),
    'ccm_mixing':       preset('P64X64_1_32', color='.ccm_rg_shift = 6, .ccm_gb_shift = 7, .ccm_br_shift = 8'),

    # --- 4 rows lit per address instead of 2 ---
    'rowmap_s31':       preset('P64X32_1_16', panel='.panel_kind = RowMapping::S31, .scan_mode = 8'),
    'rowmap_split':     preset('P64X32_1_16', panel='.panel_kind = RowMapping::Split, .scan_mode = 8'),

    # --- panel chip init sequences (each is a different PIO program) ---
    'chip_rul6024':     preset('P64X64_1_32', panel='.panel_chip = Hub75PanelChip::RUL6024'),
    'chip_fm6126a':     preset('P64X64_1_32', panel='.panel_chip = Hub75PanelChip::FM6126A'),

    # --- timing and wiring ---
    'inverted_stb':     preset('P64X64_1_32', panel='.inverted_stb = true'),
    'slow_state_machine': preset('P64X64_1_32', panel='.sm_clockdiv_factor = 8.0f'),
    'fast_timing':      preset('P64X64_1_32', panel='.base_latch_ns = 40, .base_addr_ns = 60'),
    'low_clockdiv':     preset('P64X64_1_32', panel='.sm_clockdiv_factor = 0.5f'),

    # --- orientation ---
    'rot90':            preset('P64X64_1_32', screen='.rotation = Hub75Rotation::DEG_90'),
    'rot270':           preset('P64X64_1_32', screen='.rotation = Hub75Rotation::DEG_270'),

    # --- chaining ---
    'chain_2x2':        preset('P64X32_1_16', panel='.chain_rows = 2, .chain_cols = 2'),
    'chain_1x4':        preset('P64X32_1_16', panel='.chain_rows = 1, .chain_cols = 4'),

    # --- explicit scan_mode overriding the derived value ---
    # The 96x48 preset with scan_mode 16 would divide to 3 rows lit, which the
    # ROWS_IN_PARALLEL assert correctly rejects; 64x64 at scan_mode 16 gives the
    # 4-rows-lit case, exercising the override without a rejected depth.
    'explicit_scan_mode': preset('P64X64_1_32', panel='.scan_mode = 16'),
}

TEMPLATE = '''\
// GENERATED by tests/gen_compile_tests.py - do not edit.
//
// Instantiating the driver is enough to exercise the compile-time contract:
// every class-scope static_assert in Hub75DriverBase fires on instantiation.
// Nothing is called and nothing is linked, so this TU stays fast.

#include "pico/stdlib.h"
#include "hub75.hpp"

namespace {
constexpr Hub75Config Cfg = __CFG__;
using Driver = Hub75Driver<Cfg>;
static Driver driver;
} // namespace
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--outdir', required=True, help='directory to write the TUs into')
    args = ap.parse_args()

    cases = {p.lower(): preset(p) for p in PRESETS}
    cases.update(CASES)

    out = pathlib.Path(args.outdir)
    out.mkdir(parents=True, exist_ok=True)
    for name, expr in cases.items():
        (out / f'{name}.cpp').write_text(TEMPLATE.replace('__CFG__', expr))
    print(f'wrote {len(cases)} compile-test TUs to {out}', file=sys.stderr)


if __name__ == '__main__':
    main()
